    is_railways_enabled               BOOLEAN,
    is_topup_enabled                  BOOLEAN,
    is_movie_enabled                  BOOLEAN,
    is_ksrtc_enabled                  BOOLEAN,
    is_charge_payment_fee             BOOLEAN,
    is_give_plb_despite_no_payment_fee BOOLEAN,
    cug                               BOOLEAN,
    net_banking_enabled               BOOLEAN,
    user_priveledges                  VARCHAR(101),
    prefix_code                       VARCHAR(20),
    CONSTRAINT pk_users PRIMARY KEY (user_id),

    CONSTRAINT users_email_key  UNIQUE (role, email, login_partner_id),
    CONSTRAINT users_mobile_key UNIQUE (role, mobile, login_partner_id)
);

CREATE TABLE user_hist (
    user_id   BIGINT NOT NULL,
    create_ts TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    history   TEXT NOT NULL,
    CONSTRAINT pk_uhist FOREIGN KEY (user_id) REFERENCES users (user_id)
        ON UPDATE NO ACTION ON DELETE NO ACTION
);
