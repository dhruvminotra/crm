    dist_credit_onetime               INT4,
    dist_credit_rolling               BIGINT,
    dist_credit_locktime              TIMESTAMP,
    credit_lock_date                  TIMESTAMP,
    low_balance_alert_limit           INT4,
    commission_rate                   NUMERIC(5,2),
    hotel_commission_rate             NUMERIC(5,2),
    hotel_sa_commission_rate          NUMERIC(5,2),
    bus_sa_commission_rate            NUMERIC(5,2),
    package_sa_commission_rate        NUMERIC(5,2) DEFAULT 2.0,
    movie_sa_commission_rate          NUMERIC(5,2),
    topup_commission_rate             NUMERIC(5,2) DEFAULT 2.0,
    topup_sa_commission_rate          NUMERIC(5,2),
    topup_commplan_id                 INT4,
    flight_comm_plan_id               INT4 DEFAULT -1,
    flight_commissions                TEXT,
    agent_markup                      TEXT,
    tds_rate                          NUMERIC(5,2),
    tds_slab                          INT4,
