    a_state                           VARCHAR(51)  DEFAULT '',
    a_pincode                         VARCHAR(11)  DEFAULT '',
    a_country                         VARCHAR(51)  DEFAULT '',
    locality_id                       INT4,
    locality                          VARCHAR(151),
    longitude                         FLOAT8,
