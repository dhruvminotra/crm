    cash_limit                        BIGINT,
    rolling_credit_max                INT4,
    rolling_credit_exhausted          INT4,
    is_credit_enabled                 BOOLEAN,
    is_credit_card_enabled            BOOLEAN,
    is_deposit_enabled                BOOLEAN,
